    학년,
    학기,
    반영교과,
    점수구분,
    과목명;


/* ============================================================
   11. 최종 반영과목만 분리

   - 석차등급 과목: 반영 조건을 충족한 전 과목
   - 진로선택과목: 지원자별 상위 3과목
   ============================================================ */
DROP TABLE IF EXISTS #고교추천_최종반영과목;

SELECT
    수험번호,
    전형코드,
    전형명,
    계열,
    계열명,
    모집단위코드,
    모집단위명,
    학과부코드,

    학년,
    학기,

    편제코드,
    편제명,
    반영교과,

