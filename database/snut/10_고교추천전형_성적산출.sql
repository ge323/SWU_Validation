/* ============================================================
   1. 학생부 편제명을 서울과기대 반영교과로 분류
   ============================================================ */
WITH 과목분류 AS
(
    SELECT
        S.입학연도,
        S.모집시기,
        S.수험번호,
        S.학년,
        S.학기,

        S.편제코드,
        S.편제명,

        S.교과코드,
        S.교과명,

        S.과목코드,
        S.과목명,

        S.이수단위,
        S.석차,
        S.재적수,
        S.동석차,
        S.원점수,
        S.평균,
        S.표준편차,
        S.석차등급,
        S.성취도,
        S.과목구분_02_진로교과,

        CASE
            WHEN S.편제명 = N'국어'
                THEN N'국어'

            WHEN S.편제명 = N'영어'
                THEN N'영어'

            WHEN S.편제명 = N'수학'
                THEN N'수학'

            WHEN S.편제명 IN
            (
                N'과학',
                N'과학 계열',
                N'과학에관한교과'
            )
                THEN N'과학'

            WHEN S.편제명 IN
            (
                N'사회',
                N'사회 계열',
                N'사회(역사/도덕포함)',
                N'사회에관한교과'
            )
                THEN N'사회'

            WHEN S.편제명 = N'한국사'
                THEN N'한국사'

            ELSE N'기타'
        END AS 반영교과

    FROM dbo.HsbSubjectScore AS S
),


/* ============================================================
   2. 고교추천전형 지원자와 학생부 과목 연결
   ============================================================ */
지원자과목 AS
(
    SELECT
        A.수험번호,

        A.전형코드,
        A.전형명,

        A.계열,
        A.계열명,

        A.모집단위코드,
        A.모집단위명,
        A.학과부코드,

        S.학년,
        S.학기,

        S.편제코드,
        S.편제명,
        S.반영교과,

        S.교과코드,
        S.교과명,

        S.과목코드,
        S.과목명,

        S.이수단위,
        S.석차,
        S.재적수,
        S.동석차,
        S.원점수,
        S.평균,
        S.표준편차,
        S.석차등급,
        S.성취도,
        S.과목구분_02_진로교과

    FROM dbo.vwApplyInfo AS A

    INNER JOIN 과목분류 AS S
        ON A.수험번호 = S.수험번호

    WHERE A.전형명 = N'고교추천전형'

      /* 3학년 1학기까지만 반영 */
      AND
      (
          S.학년 IN (1, 2)

          OR
          (
              S.학년 = 3
              AND S.학기 = 1
          )
      )
),


/* ============================================================
   3. 모집단위 계열별 반영 교과 판정
   ============================================================ */
반영교과판정 AS
(
    SELECT
        J.*,

        CASE
            /* 건축학부 건축학전공 */
            WHEN J.모집단위명 = N'건축학부(건축학전공)'
             AND J.반영교과 IN
                 (
                     N'국어',
                     N'영어',
                     N'수학',
                     N'과학',
                     N'사회',
                     N'한국사'
                 )
                THEN 1

            /* 자연계열 */
            WHEN J.계열명 = N'자연'
             AND J.모집단위명 <> N'건축학부(건축학전공)'
             AND J.반영교과 IN
                 (
                     N'국어',
                     N'영어',
                     N'수학',
                     N'과학'
                 )
                THEN 1

            /* 인문계열 */
            WHEN J.계열명 = N'인문'
             AND J.반영교과 IN
                 (
                     N'국어',
                     N'영어',
                     N'수학',
                     N'사회',
                     N'한국사'
                 )
                THEN 1

            ELSE 0
        END AS 반영교과여부

    FROM 지원자과목 AS J
),


/* ============================================================
   4. 석차등급과 성취도 값 정리
   ============================================================ */
값정리 AS
(
    SELECT
        G.*,

        TRY_CONVERT
        (
            int,
            NULLIF
            (
                LTRIM(RTRIM(G.석차등급)),
                ''
            )
        ) AS 석차등급숫자,

        UPPER
        (
            NULLIF
            (
                LTRIM(RTRIM(G.성취도)),
                ''
            )
        ) AS 성취도정리

    FROM 반영교과판정 AS G
),


/* ============================================================
   5. 과목 점수구분 및 반영점수 산출
   ============================================================ */
점수판정 AS
(
    SELECT
        V.*,

        CASE
            /* 석차등급 1~9가 있는 과목 */
            WHEN V.석차등급숫자 BETWEEN 1 AND 9
                THEN N'석차등급'

            /* 진로선택과목이며 성취도 A/B/C인 과목 */
            WHEN V.과목구분_02_진로교과 = 2
             AND V.성취도정리 IN (N'A', N'B', N'C')
                THEN N'진로선택'

            ELSE N'미반영'
        END AS 점수구분,

        /* 고교추천전형 석차등급별 반영점수 */
        CASE V.석차등급숫자
            WHEN 1 THEN 1000
            WHEN 2 THEN 990
            WHEN 3 THEN 980
            WHEN 4 THEN 970
            WHEN 5 THEN 960
            WHEN 6 THEN 800
            WHEN 7 THEN 500
            WHEN 8 THEN 250
            WHEN 9 THEN 0
            ELSE NULL
        END AS 석차등급반영점수,

        /* 고교추천전형 진로선택 성취도별 반영점수 */
        CASE V.성취도정리
            WHEN N'A' THEN 1000
            WHEN N'B' THEN 980
            WHEN N'C' THEN 800
            ELSE NULL
        END AS 성취도반영점수

    FROM 값정리 AS V
),


/* ============================================================
   6. 반영 가능 여부 판정
   ============================================================ */
반영후보판정 AS
(
    SELECT
        P.*,

        CASE
            WHEN P.반영교과여부 = 0
                THEN N'계열별 미반영 교과'

            WHEN P.이수단위 IS NULL
              OR P.이수단위 <= 0
                THEN N'이수단위 없음'

            /* 공통·일반선택 등 석차등급 과목 필수항목 */
            WHEN P.점수구분 = N'석차등급'
             AND
                 (
                     P.원점수 IS NULL
                     OR P.평균 IS NULL
                     OR P.표준편차 IS NULL
                     OR P.재적수 IS NULL
                     OR P.재적수 <= 0
                 )
                THEN N'석차등급 과목 필수값 누락'

            /* 진로선택과목 필수항목 */
            WHEN P.점수구분 = N'진로선택'
             AND
                 (
                     P.원점수 IS NULL
                     OR P.평균 IS NULL
                     OR P.재적수 IS NULL
                     OR P.재적수 <= 0
                 )
                THEN N'진로선택 과목 필수값 누락'

            WHEN P.점수구분 = N'미반영'
                THEN N'석차등급·진로선택 조건 불충족'

            ELSE N'반영후보'
        END AS 반영판정

    FROM 점수판정 AS P
)


/* ============================================================
   7. 반영 후보 과목 임시 테이블 생성
   ============================================================ */
SELECT
    R.*,

    CASE
        WHEN R.반영교과여부 = 1
         AND R.점수구분 = N'석차등급'
         AND R.반영판정 = N'반영후보'
            THEN R.석차등급반영점수

        WHEN R.반영교과여부 = 1
         AND R.점수구분 = N'진로선택'
         AND R.반영판정 = N'반영후보'
            THEN R.성취도반영점수

        ELSE NULL
    END AS 과목반영점수

INTO #고교추천_과목후보

FROM 반영후보판정 AS R;
GO


/* ============================================================
   8. 진로선택과목만 분리하여 지원자별 순위 산정

   중요:
   기존처럼 전체 과목을 대상으로 ROW_NUMBER를 계산하지 않고,
   진로선택 반영후보만 따로 분리한 뒤 순위를 계산함.

   임시 동점 정렬 기준:
   1) 성취도 반영점수 높은 순
   2) 이수단위 높은 순
   3) 원점수 높은 순
   4) 학년, 학기, 과목코드 순

   ※ 2~4번 동점 기준은 모집요강에 명시되어 있지 않음.
      내부 성적산출 기준 확인 후 수정 필요.
   ============================================================ */
SELECT
    H.수험번호,
    H.학년,
    H.학기,
    H.편제코드,
    H.과목코드,

    ROW_NUMBER() OVER
    (
        PARTITION BY H.수험번호

        ORDER BY
            H.성취도반영점수 DESC,
            H.이수단위 DESC,
            H.원점수 DESC,
            H.학년 ASC,
            H.학기 ASC,
            H.과목코드 ASC
    ) AS 진로선택순위

INTO #고교추천_진로순위

FROM #고교추천_과목후보 AS H

WHERE H.반영판정 = N'반영후보'
  AND H.점수구분 = N'진로선택';
GO


/* ============================================================
   9. 과목 후보와 진로선택 순위 연결
   ============================================================ */
SELECT
    H.수험번호,

    H.전형코드,
    H.전형명,

    H.계열,
    H.계열명,

    H.모집단위코드,
    H.모집단위명,
    H.학과부코드,

    H.학년,
    H.학기,

    H.편제코드,
    H.편제명,
    H.반영교과,

    H.교과코드,
    H.교과명,

    H.과목코드,
    H.과목명,

    H.이수단위,
    H.석차,
    H.재적수,
    H.동석차,
    H.원점수,
    H.평균,
    H.표준편차,

    H.석차등급,
    H.석차등급숫자,

    H.성취도,
    H.성취도정리,

    H.과목구분_02_진로교과,

    H.반영교과여부,
    H.점수구분,

    H.석차등급반영점수,
    H.성취도반영점수,
    H.과목반영점수,

    H.반영판정,

    J.진로선택순위,

    CASE
        WHEN H.반영판정 <> N'반영후보'
            THEN N'미반영'

        /* 석차등급 과목은 조건 충족 시 전 과목 반영 */
        WHEN H.점수구분 = N'석차등급'
            THEN N'최종반영'

        /* 진로선택과목은 지원자별 상위 3과목 반영 */
        WHEN H.점수구분 = N'진로선택'
         AND J.진로선택순위 <= 3
            THEN N'최종반영'

        WHEN H.점수구분 = N'진로선택'
         AND J.진로선택순위 > 3
            THEN N'진로선택 상위 3과목 제외'

        ELSE N'미반영'
    END AS 최종반영여부

INTO #고교추천_최종결과

FROM #고교추천_과목후보 AS H

LEFT JOIN #고교추천_진로순위 AS J
    ON H.수험번호 = J.수험번호
   AND H.학년 = J.학년
   AND H.학기 = J.학기
   AND H.편제코드 = J.편제코드
   AND H.과목코드 = J.과목코드;
GO


/* ============================================================
   10. 전체 과목 판정 결과 조회
   ============================================================ */
SELECT
