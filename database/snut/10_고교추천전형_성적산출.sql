    전형명,
    계열명,
    모집단위명,

    학년,
    학기,

    편제명,
    반영교과,
    과목명,

    이수단위,
    원점수,
    평균,
    표준편차,
    재적수,

    석차등급,
    성취도,
    과목구분_02_진로교과,

    점수구분,
    과목반영점수,

    반영판정,
    진로선택순위,
    최종반영여부

FROM #고교추천_최종결과

ORDER BY
