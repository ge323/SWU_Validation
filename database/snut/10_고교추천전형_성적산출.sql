  AND 과목반영점수 IS NOT NULL
  AND 이수단위 IS NOT NULL
  AND 이수단위 > 0;
GO


/* ============================================================
   12. 지원자별 학생부교과 점수 산출

   산출식:
   Σ(과목반영점수 × 이수단위)
   ────────────────────────
             Σ이수단위

   ※ 석차등급 과목과 진로선택 상위 3과목을
      하나로 합산하여 가중평균함
   ============================================================ */
DROP TABLE IF EXISTS #고교추천_점수산출;

SELECT
    F.수험번호,

    MAX(F.전형코드) AS 전형코드,
    MAX(F.전형명) AS 전형명,

    MAX(F.계열) AS 계열,
    MAX(F.계열명) AS 계열명,

    MAX(F.모집단위코드) AS 모집단위코드,
    MAX(F.모집단위명) AS 모집단위명,
    MAX(F.학과부코드) AS 학과부코드,

    COUNT(*) AS 최종반영과목수,

    SUM
    (
        CASE
            WHEN F.점수구분 = N'석차등급'
                THEN 1
            ELSE 0
        END
    ) AS 석차등급반영과목수,

    SUM
    (
        CASE
            WHEN F.점수구분 = N'진로선택'
                THEN 1
            ELSE 0
        END
    ) AS 진로선택반영과목수,

    SUM
    (
        CONVERT(decimal(18,4), F.이수단위)
    ) AS 최종반영이수단위합,

    SUM
    (
        CONVERT(decimal(18,4), F.과목반영점수)
        * CONVERT(decimal(18,4), F.이수단위)
    ) AS 가중점수합,

    /* 반올림 전 원점수 */
    CAST
    (
        SUM
        (
            CONVERT(decimal(18,4), F.과목반영점수)
            * CONVERT(decimal(18,4), F.이수단위)
        )
        /
        NULLIF
        (
            SUM
            (
                CONVERT(decimal(18,4), F.이수단위)
            ),
            0
        )
        AS decimal(18,6)
    ) AS 학생부교과점수_원값,

    /* 확인 편의를 위한 소수 둘째 자리 값 */
    CAST
    (
        ROUND
        (
            SUM
            (
                CONVERT(decimal(18,4), F.과목반영점수)
                * CONVERT(decimal(18,4), F.이수단위)
            )
            /
            NULLIF
            (
                SUM
                (
                    CONVERT(decimal(18,4), F.이수단위)
                ),
                0
            ),
            2
        )
        AS decimal(18,2)
    ) AS 학생부교과점수_소수2자리

INTO #고교추천_점수산출

FROM #고교추천_최종반영과목 AS F

GROUP BY
    F.수험번호;
GO

/* ============================================================
   13. 고교추천전형 지원자격 판정

   조건:
   1. 반영 교과가 존재하는 학기 3개 이상
   2. 계열별 반영 교과 이수단위 80단위 이상

   주의:
   - 80단위 계산에는 반영 교과에 해당하는
     진로선택과목 이수단위를 모두 포함함
   - 진로선택 상위 3과목 제한은 점수 산출에만 적용
   ============================================================ */
DROP TABLE IF EXISTS #고교추천_지원자격;

SELECT
    H.수험번호,

    MAX(H.전형명) AS 전형명,
    MAX(H.계열명) AS 계열명,
    MAX(H.모집단위명) AS 모집단위명,

    COUNT
    (
        DISTINCT
        CASE
            WHEN H.반영교과여부 = 1
             AND H.점수구분 IN (N'석차등급', N'진로선택')
             AND H.이수단위 IS NOT NULL
             AND H.이수단위 > 0
            THEN CONCAT
                 (
                     CONVERT(varchar(10), H.학년),
                     '-',
                     CONVERT(varchar(10), H.학기)
                 )
        END
    ) AS 반영교과학기수,

    SUM
    (
        CASE
            WHEN H.반영교과여부 = 1
             AND H.점수구분 IN (N'석차등급', N'진로선택')
             AND H.이수단위 IS NOT NULL
             AND H.이수단위 > 0
            THEN CONVERT(decimal(18,4), H.이수단위)
            ELSE 0
        END
    ) AS 자격판정이수단위합,

    SUM
    (
        CASE
            WHEN H.반영교과여부 = 1
             AND H.점수구분 = N'진로선택'
             AND H.이수단위 IS NOT NULL
             AND H.이수단위 > 0
            THEN CONVERT(decimal(18,4), H.이수단위)
            ELSE 0
        END
    ) AS 진로선택전체이수단위,

    CASE
        WHEN COUNT
             (
                 DISTINCT
                 CASE
                     WHEN H.반영교과여부 = 1
                      AND H.점수구분
                          IN (N'석차등급', N'진로선택')
                      AND H.이수단위 IS NOT NULL
                      AND H.이수단위 > 0
                     THEN CONCAT
                          (
                              CONVERT(varchar(10), H.학년),
                              '-',
                              CONVERT(varchar(10), H.학기)
                          )
                 END
             ) < 3
            THEN N'부적격: 반영 교과 3개 학기 미만'

        WHEN SUM
             (
                 CASE
                     WHEN H.반영교과여부 = 1
                      AND H.점수구분
                          IN (N'석차등급', N'진로선택')
                      AND H.이수단위 IS NOT NULL
                      AND H.이수단위 > 0
                     THEN CONVERT(decimal(18,4), H.이수단위)
                     ELSE 0
                 END
             ) < 80
            THEN N'부적격: 반영 교과 80단위 미만'

        ELSE N'지원자격 충족'
    END AS 지원자격판정

INTO #고교추천_지원자격

FROM #고교추천_과목후보 AS H

GROUP BY
    H.수험번호;
GO


/* ============================================================
   14. 고교추천전형 최종 결과 조회
   ============================================================ */
SELECT
    S.수험번호,
    S.전형명,
    S.계열명,
    S.모집단위코드,
    S.모집단위명,

    Q.반영교과학기수,
    Q.자격판정이수단위합,
    Q.진로선택전체이수단위,
    Q.지원자격판정,

    S.최종반영과목수,
    S.석차등급반영과목수,
    S.진로선택반영과목수,
    S.최종반영이수단위합,

    S.가중점수합,
    S.학생부교과점수_원값,
    S.학생부교과점수_소수2자리

FROM #고교추천_점수산출 AS S

LEFT JOIN #고교추천_지원자격 AS Q
    ON S.수험번호 = Q.수험번호

ORDER BY
    S.수험번호;
GO

