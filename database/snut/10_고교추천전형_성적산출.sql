   - 계열별 반영 교과 이수단위 80단위 이상

   주의:
   - 진로선택과목은 지원자별 상위 3과목을 점수 산출에 반영함
   - 진로선택 동점 처리기준은 내부 산출 기준 확인 후 수정 필요
   - 최종 점수의 소수점 처리 기준은 별도 확인 필요
