   - 최고점 200점
   - 최저점 120점
   =========================================================== */

IF OBJECT_ID(N'dbo.AdmissionRule', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.AdmissionRule
    (
        규칙ID int IDENTITY(1,1) NOT NULL
            CONSTRAINT PK_AdmissionRule PRIMARY KEY,

        입학연도 int NOT NULL,
        모집시기 int NOT NULL,
        전형코드 nvarchar(50) NOT NULL,
        모집단위코드 nvarchar(50) NULL,

        적용전형유형 nvarchar(100) NOT NULL,

        학생부반영비율 decimal(5,2) NOT NULL,
        실기반영비율 decimal(5,2) NOT NULL,

        학생부최고점 decimal(10,2) NOT NULL,
        학생부최저점 decimal(10,2) NOT NULL,
        전형총점 decimal(10,2) NOT NULL,

        적용우선순위 int NOT NULL,

        사용여부 bit NOT NULL
            CONSTRAINT DF_AdmissionRule_사용여부 DEFAULT 1,

        비고 nvarchar(500) NULL,

        생성일시 datetime2(0) NOT NULL
            CONSTRAINT DF_AdmissionRule_생성일시 DEFAULT SYSDATETIME(),

        수정일시 datetime2(0) NOT NULL
            CONSTRAINT DF_AdmissionRule_수정일시 DEFAULT SYSDATETIME()
    );
END;
GO


