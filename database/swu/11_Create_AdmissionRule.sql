   파일명: 11_Create_AdmissionRule.sql

   목적:
   수시 모집시기·전형·모집단위별 학생부 반영 규칙을 관리한다.

   모집시기
   - 1: 수시 1차
   - 2: 수시 2차

   기본 학생부 전형
   - 학생부 100%
   - 최고점 1,000점
   - 최저점 920점

   실기학과 예외
   - 수시 1차 일반전형
